#!/usr/bin/env node
/**
 * Records the public API of the released artifacts, so that a later accidental break is visible
 * before it is published rather than after.
 *
 * Two baselines, both plain text and both committed:
 *
 *   release/api/typescript.txt   every exported declaration of the five public npm packages
 *   release/api/java.txt         every public and protected member of the three Maven artifacts
 *
 * The TypeScript side reads the generated `.d.ts` with the TypeScript compiler, which is the only
 * thing that agrees with what a consumer's editor will see. The Java side reads the published jars
 * with `javap`, which ships with every JDK. Neither adds a tool that could stop working.
 *
 * What is deliberately not recorded: anything internal, and any implementation detail. A baseline
 * that changed whenever a private field moved would be noise, and noise gets regenerated without
 * being read.
 *
 *   node release/api-baseline.mjs            compare, and fail on a difference
 *   node release/api-baseline.mjs --update   rewrite the baselines
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const contract = JSON.parse(readFileSync(join(ROOT, 'release', 'release.json'), 'utf8'));
const { productVersion, npm, maven, runtimes } = contract;
const API = join(ROOT, 'release', 'api');
const require_ = createRequire(join(ROOT, 'ts', 'package.json'));

/** Every exported name of one declaration file, with what kind of thing it is. */
function typescriptSurface(ts, file) {
  const program = ts.createProgram([file], {
    target: ts.ScriptTarget.ESNext,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    declaration: true,
    skipLibCheck: true,
    noEmit: true,
  });
  const source = program.getSourceFile(file);
  if (source === undefined) throw new Error(`${file} could not be read`);
  const checker = program.getTypeChecker();
  const module = checker.getSymbolAtLocation(source);
  if (module === undefined) return [];
  const entries = [];
  for (const symbol of checker.getExportsOfModule(module)) {
    const declaration = symbol.declarations?.[0];
    if (declaration === undefined) continue;
    const kind = ts.SyntaxKind[declaration.kind]
      .replace(/Declaration$/u, '')
      .replace(/Statement$/u, '')
      .toLowerCase();
    entries.push(`${kind} ${symbol.getName()}`);
  }
  return entries.sort();
}

function typescriptBaseline() {
  const ts = require_('typescript');
  const lines = [
    '# The exported surface of the public qe-report npm packages.',
    '# Generated by release/api-baseline.mjs from the built declarations. Do not edit by hand.',
    `# product version ${productVersion}`,
    '',
  ];
  for (const name of npm.public) {
    const directory = name.replace(/^qe-report-/u, '');
    const dist = join(ROOT, 'ts', 'packages', directory, 'dist');
    if (!existsSync(dist)) throw new Error(`${name} has not been built`);
    lines.push(`## ${name}`);
    // Every entry point the package publishes, not only its main one.
    const declarations = readdirSync(dist)
      .filter((f) => f.endsWith('.d.ts') && !f.includes('-'))
      .sort();
    for (const file of declarations) {
      lines.push(`# ${file}`);
      for (const entry of typescriptSurface(ts, join(dist, file))) lines.push(`  ${entry}`);
    }
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

/** A JDK of the published bytecode floor, so the baseline describes what a consumer compiles against. */
function javaHome(version) {
  const candidates = [
    process.env.QE_REPORT_JAVA17_HOME,
    process.env[`JAVA_HOME_${version}_X64`],
    process.env[`JAVA_HOME_${version}_arm64`],
    process.env.JAVA_HOME,
  ].filter((c) => typeof c === 'string' && c !== '');
  const provisioned = join(homedir(), '.gradle', 'jdks');
  if (existsSync(provisioned)) {
    for (const entry of readdirSync(provisioned)) {
      if (!entry.includes(`-${version}-`)) continue;
      const base = join(provisioned, entry);
      try {
        for (const inner of readdirSync(base)) {
          for (const home of [join(base, inner), join(base, inner, 'Contents', 'Home')]) {
            if (existsSync(join(home, 'bin', 'javap'))) candidates.push(home);
          }
        }
      } catch {
        continue;
      }
    }
  }
  for (const candidate of candidates) {
    if (existsSync(join(candidate, 'bin', 'javap'))) return candidate;
  }
  throw new Error(`no JDK with javap found for Java ${version}`);
}

function javaBaseline() {
  const home = javaHome(runtimes.javaBytecode);
  const javap = join(home, 'bin', 'javap');
  const staging = join(ROOT, 'java', 'build', 'release-staging', ...maven.groupId.split('.'));
  const lines = [
    '# The public surface of the published qe-report Maven artifacts.',
    '# Generated by release/api-baseline.mjs with javap over the staged jars. Do not edit by hand.',
    `# product version ${productVersion}, bytecode ${runtimes.javaBytecode}`,
    '',
  ];
  for (const artifactId of maven.public) {
    const jar = join(staging, artifactId, productVersion, `${artifactId}-${productVersion}.jar`);
    if (!existsSync(jar)) throw new Error(`${jar} is missing; stage the release first`);
    lines.push(`## ${maven.groupId}:${artifactId}`);
    const listed = spawnSync('unzip', ['-Z1', jar], { encoding: 'utf8' }).stdout ?? '';
    const classes = listed
      .split('\n')
      .map((l) => l.trim())
      .filter((l) => l.endsWith('.class') && !l.includes('$'))
      .map((l) => l.replace(/\.class$/u, '').replaceAll('/', '.'))
      // Anything internal is excluded from the guarantee, so it is excluded from the baseline.
      .filter((c) => !c.includes('.internal.') && !c.endsWith('.package-info'))
      .sort();
    for (const className of classes) {
      const shown = spawnSync(javap, ['-protected', '-classpath', jar, className], {
        encoding: 'utf8',
        maxBuffer: 16 * 1024 * 1024,
      });
      if (shown.status !== 0) throw new Error(`javap failed for ${className}`);
      for (const line of (shown.stdout ?? '').split('\n')) {
        const member = line.trim();
        if (member === '' || member === '}') continue;
        // Normalised: javap prints "Compiled from" and the declaration, both stable, and nothing
        // about a build machine.
        if (member.startsWith('Compiled from')) continue;
        lines.push(`  ${member}`);
      }
    }
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

const update = process.argv.includes('--update');
mkdirSync(API, { recursive: true });
const baselines = [
  { file: join(API, 'typescript.txt'), produce: typescriptBaseline, what: 'TypeScript' },
  { file: join(API, 'java.txt'), produce: javaBaseline, what: 'Java' },
];

const problems = [];
for (const baseline of baselines) {
  const produced = baseline.produce();
  if (update || !existsSync(baseline.file)) {
    writeFileSync(baseline.file, produced);
    process.stdout.write(`${update ? 'updated' : 'created'} the ${baseline.what} API baseline\n`);
    continue;
  }
  const recorded = readFileSync(baseline.file, 'utf8');
  if (recorded === produced) {
    const surface = produced.split('\n').filter((l) => l.startsWith('  ')).length;
    process.stdout.write(`the ${baseline.what} API baseline matches: ${surface} declarations\n`);
    continue;
  }
  const recordedLines = new Set(recorded.split('\n'));
  const producedLines = new Set(produced.split('\n'));
  const removed = [...recordedLines].filter((l) => l.startsWith('  ') && !producedLines.has(l));
  const added = [...producedLines].filter((l) => l.startsWith('  ') && !recordedLines.has(l));
  problems.push(
    `the ${baseline.what} API changed: ${removed.length} declarations gone, ${added.length} new\n` +
      [
        ...removed.slice(0, 12).map((l) => `      - ${l.trim()}`),
        ...added.slice(0, 12).map((l) => `      + ${l.trim()}`),
      ].join('\n'),
  );
}

if (problems.length > 0) {
  process.stderr.write(
    '\nthe public API differs from the recorded baseline. If the change is intended, and the\n' +
      'product version allows it, re-run with --update and commit the result:\n\n',
  );
  for (const problem of problems) process.stderr.write(`  ${problem}\n`);
  process.exit(1);
}
